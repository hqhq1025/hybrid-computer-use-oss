#!/usr/bin/env bash
# Remove history-only version markers (AXSnapshotV1, ProviderV2*, *_v2.go,
# wire_v2.py, testdata/provider-v2/, the wire value "computer-use-provider-v2")
# and retired concept file names (ax_until_*, ax_postcondition*) from names.
#
# Usage (repository root, clean tree):
#   scripts/maint/drop_version_names.sh measure          # plan and collisions, no edits
#   scripts/maint/drop_version_names.sh map              # old -> new table
#   scripts/maint/drop_version_names.sh apply [--commit]
#
# apply runs drop_version_names.py (git mv and whole-token rewrites), gofmt
# on the changed Go files, go build and go vet for linux, darwin and windows
# (and linux with the sidecar test tags), and check_layout.sh. With --commit it commits the result.
#
# The rules match names, not a file list, so the script can be re-run on any
# later main after other branches merge: it also renames files and
# identifiers those branches added under the old names, and it stops with a
# list when a new name already exists. On its own output it reports
# "nothing to rename". Rules and the kept exceptions are documented in
# drop_version_names.py.
set -euo pipefail

repo=$(git rev-parse --show-toplevel)
cd "$repo"
export PATH="$HOME/.local/bin:$PATH"
tool=scripts/maint/drop_version_names.py

mode=${1:-measure}
case "$mode" in
measure | map)
	python3 "$tool" "$mode"
	;;
apply)
	python3 "$tool" apply
	git add -A
	# Shorter names change column alignment; gofmt restores it.
	mapfile -t go_files < <(git diff --cached --name-only --diff-filter=AMR -- '*.go')
	if [ "${#go_files[@]}" -gt 0 ]; then
		gofmt -w "${go_files[@]}"
		git add -A
	fi
	(
		cd computer-use
		for goos in linux darwin windows; do
			GOOS=$goos go build ./...
			GOOS=$goos go vet ./...
		done
		# The sidecar test tags build darwin and windows transports on Linux.
		GOOS=linux go vet -tags 'darwin_sidecar_test windows_sidecar_test' ./...
	)
	scripts/maint/check_layout.sh
	if [ "${2:-}" = "--commit" ] && ! git diff --cached --quiet; then
		git commit -q -m "refactor: drop history-only version markers from names

Generated by scripts/maint/drop_version_names.sh apply."
		git log --oneline -1
	fi
	;;
*)
	echo "usage: $0 measure|map|apply [--commit]" >&2
	exit 2
	;;
esac
